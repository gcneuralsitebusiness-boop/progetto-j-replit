import { pgTable, serial, integer, real, text, date, timestamp, boolean, numeric, time, unique } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";
import { z } from "zod/v4";

export const giorniTable = pgTable("giorni", {
  id: serial("id").primaryKey(),
  numero: integer("numero").notNull(),
  fase: integer("fase").notNull().default(1),
  roundSparring: integer("round_sparring"),
  roundPao: integer("round_pao"),
  roundTecnica: integer("round_tecnica"),
  oraSveglia: time("ora_sveglia"),
  oreLavoro: numeric("ore_lavoro", { mode: "number" }),
  risparmio: numeric("risparmio", { mode: "number" }),
  entrateOnline: numeric("entrate_online", { mode: "number" }),
  videoPubblicati: integer("video_pubblicati"),
  articoliPubblicati: integer("articoli_pubblicati"),
  follower: integer("follower"),
  pagineLette: integer("pagine_lette"),
  minutiScrittura: integer("minuti_scrittura"),
  data: date("data", { mode: "string" }).notNull(),
  kcal: integer("kcal"),
  pasti: integer("pasti"),
  alcol: boolean("alcol"),
  acqua: real("acqua"),
  acquaAllenamento: real("acqua_allenamento"),
  tipoAllenamento: text("tipo_allenamento"),
  durata: real("durata"),
  intensita: integer("intensita"),
  tipoGiorno: text("tipo_giorno"),
  routineCompletata: boolean("routine_completata"),
  routineForza: boolean("routine_forza"),
  routineFlessioni: text("routine_flessioni"),
  routineTrazioni: text("routine_trazioni"),
  routineSquat: text("routine_squat"),
  plank: integer("plank"),
  collo: boolean("collo"),
  mobilita: boolean("mobilita"),
  sollevamentoGamba: text("sollevamento_gamba"),
  grapplingVuoto: boolean("grappling_vuoto"),
  energia: integer("energia"),
  noteAllenamento: text("note_allenamento"),
  sonno: real("sonno"),
  flessioni: integer("flessioni"),
  addominali: integer("addominali"),
  squat: integer("squat"),
  stretchingMin: integer("stretching_min"),
  round: integer("round"),
  km: real("km"),
  peso: real("peso"),
  battito: integer("battito"),
  entrate: real("entrate"),
  uscite: real("uscite"),
  testo: text("testo"),
  sintesi: text("sintesi"),
  foto: text("foto"),
  attrito: text("attrito"),
  stato1pct: text("stato_1pct"),
  fronteSettimana: text("fronte_settimana"),
  nota1pct: text("nota_1pct"),
  fatto: text("fatto"),
  nonFatto: text("non_fatto"),
  cardTitolo: text("card_titolo"),
  cardSottotitolo: text("card_sottotitolo"),
  cardImmagine: text("card_immagine"),
  cardOverlay: integer("card_overlay"),
  cardMostraParole: boolean("card_mostra_parole"),
  cardFeed: text("card_feed"),
  cardStory: text("card_story"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (table) => [unique("giorni_fase_numero_unique").on(table.fase, table.numero)]);

export const insertGiornoSchema = createInsertSchema(giorniTable).omit({
  id: true,
  createdAt: true,
});

export type InsertGiorno = z.infer<typeof insertGiornoSchema>;
export type Giorno = typeof giorniTable.$inferSelect;
